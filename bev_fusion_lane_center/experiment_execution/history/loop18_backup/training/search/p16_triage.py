def pooled(s, rung):
    """effects of the three factors of a rung, pooled over the survivors: mean of the level-2 branches minus mean of the level-1 branches (per design), then the mean over the designs"""
    sp, band = noise_band(control_table())
    sigma = (sp / 1.13) if not np.isnan(sp) else 0.01
    out = []
    for fi in range(3):
        keys = ("S", "vert100", "FL@R85", "F1@Sp17")
        eff = {k: [] for k in keys}
        for d in sorted({r["design"] for r in s["runs"].values() if r["rung"] == rung and r["type"] == "F"}):
            cs = {b: card(run_name(d, rung, b)) for b in ("b1", "b2", "b3", "b4")}
            if any(c is None or "metrics" not in c for c in cs.values()):
                continue
            hi, lo = L4[fi]
            def val(c, k):
                return c["metrics"][k] if k in ("S", "vert100") else c.get(k)
            for k in keys:
                a = [val(cs[b], k) for b in hi]
                b_ = [val(cs[b], k) for b in lo]
                if all(x is not None and not (isinstance(x, float) and np.isnan(x)) for x in a + b_):
                    eff[k].append(float(np.mean(a) - np.mean(b_)))
        out.append({k: (float(np.mean(v)) if v else None) for k, v in eff.items()} | dict(n=len(eff["S"])))
    return out, 0.71 * max(sigma, 0.005) * np.sqrt(2.0 / max(1, out[0]["n"])) if out and out[0]["n"] else None


def tbl_pooled(s):
    out = ["| rung | factor | level 1 | level 2 | effect on S | effect on vertices per 100 m | effect on FL@R85 | effect on F1@Sp17 | SE | supported | basis |\n|" + "---|" * 11]
    for rung in (1, 2):
        eff, se = pooled(s, rung)
        for fi, (name, l1, l2, basis) in enumerate(FACT[rung]):
            e = eff[fi]
            sup = (abs(e["S"]) > 2 * se) if (e["S"] is not None and se) else None
            out.append(f"| {rung} | {name} | {l1} | {l2} | {fmt(e['S'])} | {fmt(e['vert100'], 1)} | {fmt(e['FL@R85'])} | {fmt(e['F1@Sp17'])} | {fmt(se) if se else '—'} | {('yes' if sup else 'no') if sup is not None else '—'} | {basis} |")
    return "\n".join(out)


