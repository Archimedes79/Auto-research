def is_running(name):
    return os.path.exists(f"{C.OUT}/e123/{name}") and not os.path.exists(f"{C.OUT}/e123/{name}.done") and card(name) is None


def launch(s, design, rung, step, u, parent=None, sets=(), ws=(), typ="T", change="trial as specified in the L8 row", basis=None, seed=0, hypothesis=""):
    name = run_name(design, rung, step)
    args = ["bash", "/mnt/c/ML-Experiment/bev_fusion_lane_center/training/search/_run_p16.sh", design, name, str(u), "--seed", str(seed)]
    if parent:
        args += ["--init", parent]
    if sets:
        args += ["--set", *sets]
    if ws:
        args += ["--w", *ws]
    os.makedirs(f"{C.OUT}/e123", exist_ok=True)
    subprocess.Popen(args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
    s["runs"][run_id(design, rung, step)] = dict(design=design, rung=rung, step=step, type=typ, change=change, hypothesis=hypothesis, basis=basis or BASIS.get(design, ""), parent=parent or "-", u=u, seed=seed, name=name, launched=time.strftime("%Y-%m-%d %H:%M"), sets=list(sets), ws=list(ws))
    return name


def enqueue(s, design, rung, step, u, parent=None, sets=(), ws=(), typ="T", change="trial as specified in the L8 row", hyp="", basis=None, seed=0, after=(), extra=()):
    """register a run in the ledger and put it in the driver queue (queue.json); the driver launches it when a GPU slot is free and the parent card exists"""
    qp = f"{L}/queue.json"
    q = json.load(open(qp)) if os.path.exists(qp) else []
    name = run_name(design, rung, step)
    if any(f"e123_{j['design']}_r{j['rung']}_{j['step']}" == name for j in q):
        return name
    q.append(dict(design=design, rung=rung, step=step, u=u, parent=parent, sets=list(sets), ws=list(ws), seed=seed, after=list(after), extra=list(extra)))
    json.dump(q, open(qp, "w"), indent=1)
    s["runs"][run_id(design, rung, step)] = dict(design=design, rung=rung, step=step, type=typ, change=change, hypothesis=hyp, basis=basis or BASIS.get(design, ""), parent=parent or "-", u=u, seed=seed, name=name, launched="queued", sets=list(sets), ws=list(ws))
    return name


# ------------------------------------------------------------------ control arm
def control_table():
    rows = {}
    for sd in (0, 1):
        for u in (1, 2, 4, 8):
            c = card(f"e122_s{sd}_{u}u.val_clean_val250")
            rows[(sd, u)] = c["metrics"] if c else None
        c = card("e94_a.val_clean_val250" if sd == 0 else "e94_s1.val_clean_val250")
        rows[(sd, 17)] = c["metrics"] if c else None
    return rows


def builder_spread():
    """mean absolute difference of S between two seeds of the same builder trial (runs ...00 and ...00s1)"""
    d = []
    for des in DESIGNS + ["B1", "B3"]:
        a, b = card(f"e123_{des}_r0_00"), card(f"e123_{des}_r0_00s1")
        if a and b and "metrics" in a and "metrics" in b:
            d.append(abs(a["metrics"]["S"] - b["metrics"]["S"]))
    return (float(np.mean(d)) if d else float("nan")), len(d)


def noise_band(rows):
    """spread = mean |S(seed 0) - S(seed 1)|: control arm from 2 u up, and builder trials with a second seed (the larger one counts); delta = 2 x spread, at least 0.01"""
    d = [abs(rows[(0, u)]["S"] - rows[(1, u)]["S"]) for u in (2, 4, 8, 17) if rows.get((0, u)) and rows.get((1, u))]
    spread = float(np.mean(d)) if d else float("nan")
    bs, n = builder_spread()
    if n:
        spread = bs if np.isnan(spread) else max(spread, bs)
    return spread, max(0.01, 2 * spread) if not np.isnan(spread) else 0.02


