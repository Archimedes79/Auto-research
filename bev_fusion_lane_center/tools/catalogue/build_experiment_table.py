"""Builds the experiment table with its basis: catalogue (E15 - E121) + building blocks (BB) + technique register (K, with links) + stage of the sparsification chain (SP).
Also writes the K60+ rows of the register into the plan (reports/Loop16_Triage_Plan_EN.md section 10.0, idempotent).
Outputs: reports/Experiment_Table_EN.md, out/loop2/EXPERIMENT_TABLE.csv, out/loop2/EXPERIMENT_TABLE.json
Usage (gcar): build_experiment_table.py"""
import csv
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import e2e_basis as B  # noqa: E402
import e2e_catalogue as C  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))  # the problem folder
PLAN = f"{ROOT}/experiment_execution/plans/Loop16_Triage_Plan_EN.md"
OUT_MD = f"{ROOT}/experiment_execution/plans/Experiment_Table_EN.md"


def label(u):
    m = re.search(r"abs/([0-9.]+[0-9v]*)", u)
    return f"arXiv {m.group(1)}" if m else u


def reg_row(r):
    kid, tech, src, key, status, used = r
    links = B.LINKS.get(key, [])
    ltxt = "; ".join(f"[{label(u)}]({u})" for u in links)
    return f"| {kid} | {tech} | {src}{(' ' + ltxt) if ltxt else ''} | {status} | {used} |"


def kid_num(line):
    m = re.match(r"\| K(\d+) \|", line)
    return int(m.group(1)) if m else None


def update_plan():
    lines = open(PLAN, encoding="utf-8").read().split("\n")
    out, last52, in_reg = [], None, False
    for ln in lines:
        n = kid_num(ln)
        if n is not None and n >= 60:
            continue  # regenerated below
        out.append(ln)
    for i, ln in enumerate(out):
        n = kid_num(ln)
        if n is not None and n <= 52:
            last52 = i
    assert last52 is not None, "register not found in the plan"
    new = [reg_row(r) for r in B.NEWREG]
    out[last52 + 1 : last52 + 1] = new
    open(PLAN, "w", encoding="utf-8").write("\n".join(out))
    return len(new)


def parse_register():
    reg = {}
    for ln in open(PLAN, encoding="utf-8").read().split("\n"):
        if kid_num(ln) is not None:
            c = [x.strip() for x in ln.strip().strip("|").split("|")]
            if len(c) >= 5:
                reg[c[0]] = dict(tech=c[1], src=c[2], status=c[3], used=c[4])
    return reg


def first_link(src):
    m = re.search(r"\]\((https?://[^)]+)\)", src)
    return m.group(1) if m else ""


def main():
    n_new = update_plan()
    reg = parse_register()
    rows, missing, unknown = [], [], set()
    for theme, eid, what, res, tag in C.EXPS:
        b = B.EXP_BASIS.get(eid)
        if b is None:
            missing.append(eid)
            b = dict(bb=[], k=[], sp=["SP0"])
        for k in b["k"]:
            if k not in reg:
                unknown.add(k)
        rows.append(dict(theme=theme, id=eid, what=what, result=res, tag=tag, sp=b["sp"], bb=b["bb"], k=b["k"]))
    themes = {t: (n, l) for t, n, l in C.THEMES}
    md = []
    md.append("# Experiment table with its basis (E15 - E121)\n")
    md.append("Generated by `scripts/build_experiment_table.py` from `scripts/e2e_catalogue.py` (what, result, use tag), `scripts/e2e_basis.py` (basis) and the technique register in `reports/Loop16_Triage_Plan_EN.md` section 10.0 (links). Columns: **tag** = use in a completely differentiable end-to-end system (E learned and differentiable, P with a classical step, C classical / reference, D dropped); **SP** = stage of the sparsification chain the experiment addresses; **BB** = building blocks of the catalogue (`report_final/text/lit_extra10b.md` and the new blocks BB22 - BB30); **K** = technique and literature ids, links in the register below. The basis names what an experiment was derived from or inspired by according to the project's literature notes (loops 6 - 15); an empty basis means the experiment was designed from the data (no literature source named).\n")
    md.append("Sparsification stages: " + "; ".join(f"**{k}** {v}" for k, v in B.SP.items()) + ".\n")
    for t, (name, loops) in themes.items():
        md.append(f"## {t} {name} ({loops})\n")
        md.append("| id | what | result | tag | SP | BB | K |")
        md.append("|---|---|---|---|---|---|---|")
        for r in rows:
            if r["theme"] == t:
                md.append(f"| {r['id']} | {r['what']} | {r['result']} | {r['tag']} | {' '.join(r['sp'])} | {' '.join(r['bb']) or '-'} | {' '.join(r['k']) or '-'} |")
        md.append("")
    md.append("## Sparsification map: what was tried at each stage\n")
    md.append("Experiments grouped by the stage of the chain from a dense field to a sparse, correct graph (an experiment can sit in two stages). This is the starting point of the sparsification loop: what exists, what worked (tag E / P), what did not (D), and what is still open.\n")
    for sp, desc in B.SP.items():
        if sp == "SP0":
            continue
        sel = [r for r in rows if sp in r["sp"]]
        md.append(f"### {sp} {desc}\n")
        md.append("| id | tag | result (shortened) | basis |")
        md.append("|---|---|---|---|")
        for r in sel:
            md.append(f"| {r['id']} | {r['tag']} | {r['result'][:170]}{'...' if len(r['result']) > 170 else ''} | {' '.join(r['k']) or '-'} |")
        md.append("")
    cnt = {}
    for r in rows:
        for sp in r["sp"]:
            cnt.setdefault(sp, {}).setdefault(r["tag"], 0)
            cnt[sp][r["tag"]] += 1
    md.append("### Coverage count (experiments per stage and tag)\n")
    md.append("| stage | E | P | C | D | total |")
    md.append("|---|---|---|---|---|---|")
    for sp in B.SP:
        c = cnt.get(sp, {})
        md.append(f"| {sp} | {c.get('E', 0)} | {c.get('P', 0)} | {c.get('C', 0)} | {c.get('D', 0)} | {sum(c.values())} |")
    md.append("")
    md.append("## Building blocks (BB)\n")
    md.append("| id | block |")
    md.append("|---|---|")
    for k, v in B.BB.items():
        md.append(f"| {k} | {v} |")
    md.append("\n## Technique and literature register (K)\n")
    md.append("Same rows as in the plan (section 10.0), generated from it. Links only where a page was opened or seen in a search; 'from memory' = not re-checked.\n")
    md.append("| id | technique | source and link | status | used for |")
    md.append("|---|---|---|---|---|")
    for k, v in sorted(reg.items(), key=lambda kv: int(kv[0][1:])):
        md.append(f"| {k} | {v['tech']} | {v['src']} | {v['status']} | {v['used']} |")
    open(OUT_MD, "w", encoding="utf-8").write("\n".join(md) + "\n")
    # csv / json
    with open(f"{ROOT}/experiments/EXPERIMENT_TABLE.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["theme", "id", "what", "result", "tag", "sp", "bb", "k", "k_links"])
        for r in rows:
            w.writerow([r["theme"], r["id"], r["what"], r["result"], r["tag"], " ".join(r["sp"]), " ".join(r["bb"]), " ".join(r["k"]), " ".join(first_link(reg.get(k, {}).get("src", "")) for k in r["k"])])
    json.dump(dict(rows=rows, register=reg, bb=B.BB, sp=B.SP), open(f"{ROOT}/experiments/EXPERIMENT_TABLE.json", "w"), indent=1)
    print("catalogue rows", len(rows), "register rows added to plan", n_new, "missing basis for", missing, "unknown K ids", sorted(unknown))
    print("per stage", {sp: sum(c.values()) for sp, c in cnt.items()})


if __name__ == "__main__":
    main()
