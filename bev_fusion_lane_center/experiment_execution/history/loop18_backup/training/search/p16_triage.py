def rank_rung(s, rung):
    sc = {}
    for d in s.get("alive", DESIGNS):
        rs = design_runs(s, d, rung)
        if not rs:
            continue
        c = card(rs[-1][1]["name"])
        if c and "metrics" in c:
            sc[d] = c["metrics"]["S"]
    order = sorted(sc, key=lambda d: -sc[d])
    return {d: i + 1 for i, d in enumerate(order)}


