"""Write the result of a decided experiment where people look for it: results.md next to the card, the `result` column of the schedule, the result line of the research notes.

    python result.py E240          from experiments/E240_*/decision.json (written by decide.py --write): the same three records again
    python result.py E240 --check  say what would be written, change nothing

decide.py judges (KEEP / CUT / TIE / INCONCLUSIVE, the ledger token, decision.json) and calls `record()` of this file at the end of `--write`; this file never judges and every
word in it comes from decision.json and the card, no number is typed. Run it alone when the schedule item became done after the verdict, or when `sources` of the card changed.

  * results.md in the folder of the card: created with the generated block (verdict, why, effect and interval, prediction, runs, rule clauses; between the markers
    `<!-- result.py:begin ... -->` and `<!-- result.py:end -->`) and two headings for the author; later runs replace the block and keep the author's text below the end
    marker (CRLF stays CRLF); a results.md without the markers is not touched; the old markers of decide.py are replaced as well
  * the `result` column of the done schedule items whose node is the experiment: the folder (relative to the problem) that holds results.md
  * the result line of every research note the card cites in `sources` ("<topic slug>/<note id>"), then the table of each topic again (topic_table.py)
Each of the three is a side record: a failure is a printed warning and the exit code stays 0 (the verdict is in the ledger and in decision.json already)
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

GEN_BEGIN = "<!-- result.py:begin (generated by result.py; the text between the markers is replaced on every run: write below the end marker) -->"
GEN_END = "<!-- result.py:end -->"
OLD_BEGIN = re.compile(r"<!-- (?:decide|result)\.py:begin")      # decide.py wrote the same block before result.py existed
OLD_END = re.compile(r"<!-- (?:decide|result)\.py:end -->")


def results_block(d, exp):
    """the generated part of results.md: everything in it comes from the decision and the card, no number is typed"""
    one = lambda s: " ".join(str(s).split())  # noqa: E731  (one line, no stray markup of a line break)
    var, ctl = d["variant"], d["control"]
    # decision.json files of the first loops lack some keys (pairing, diffs, date): .get everywhere but for the verdict, the effect and the arms
    eff = f"{d['effect']:+.4f}" + (f", interval [{d['interval'][0]:+.4f}, {d['interval'][1]:+.4f}]" if d.get("interval") else "") + f", pairing {d.get('pairing') or 'unknown'}, {len(d.get('diffs') or [])} paired seed(s)"
    how = f"(by hand: {one(d['by_hand'])})" if d.get("by_hand") else "(rule not registered at launch)" if d.get("registered") is False else "by the rule as written"
    lines = [GEN_BEGIN,
             f"- **Card:** `experiment.md` (arm {var} against control {ctl}, headline `{d.get('metric', '?')}`)"]
    if d.get("rule_sha"):
        lines.append(f"- **Rule sha:** `{d['rule_sha']}`")
    lines += [f"- **Verdict {how}:** {d['verdict']} ({d.get('date') or 'date unknown'})",
              f"- **Why:** {one(d.get('why', ''))}",
              f"- **Effect:** {eff}"]
    if d.get("prediction"):
        lines.append(f"- **Prediction:** {one(d['prediction'])}")
    rv, rc = exp["arms"][var].get("run_ids", []), exp["arms"][ctl].get("run_ids", [])
    if rv or rc:
        lines.append(f"- **Runs:** {var}: {', '.join(rv) or '-'}; {ctl}: {', '.join(rc) or '-'}")
    lines.append("- **Rule clauses:**")
    lines += [f"  - {'ok' if c.get('ok') else 'MISS'}: {one(c.get('text', ''))}" + (f" (flags: {', '.join(c['flags'])})" if c.get("flags") else "") for c in d.get("clauses") or []]
    if d.get("cannot_tell"):
        lines.append("- **Provenance, cannot tell:** " + ", ".join(sorted({one(k).split(" ")[0] for k in d["cannot_tell"]})))
    lines.append(GEN_END)
    return "\n".join(lines)


def write_results_md(folder, d, exp):
    """results.md next to the card: created with the generated block and two headings for the author, or the block replaced when the file has the
    markers (the author's text below the end marker is kept), or left alone when it has none. Returns (path, what was done)."""
    import project as P
    path = os.path.join(folder, "results.md")
    block = results_block(d, exp)
    if not os.path.exists(path):
        text = (f"# {d['id']} result - {d['verdict']}\n\n{block}\n\n## What it says\n\n(the hypothesis, why, the negatives: written by the lead; numbers only from the block above or the metric cards)\n\n"
                "## Next\n\n(the next card or item; every question for the person with options, recommendation and evidence; his answer is recorded here with the date and his words)\n")
        P.atomic_write(path, text)
        return path, "created"
    old = open(path, encoding="utf-8", newline="").read()
    mb, me = OLD_BEGIN.search(old), OLD_END.search(old)
    if not mb or not me or me.start() < mb.start():
        return path, "exists without the markers: left as it is"
    i, j = mb.start(), me.end() - len(GEN_END)                       # j + len(GEN_END) is the end of the end marker, whichever of the two spellings it has
    nl = "\r\n" if "\r\n" in old else "\n"
    new = old[:i] + block.replace("\n", nl) + old[j + len(GEN_END):]
    new = re.sub(r"^# " + re.escape(str(d["id"])) + r" result - [^\r\n]*", f"# {d['id']} result - {d['verdict']}", new, count=1, flags=re.M)  # [^\r\n]: a CRLF stays CRLF
    P.atomic_write(path, new)
    return path, "block replaced"


def link_schedule(exp_id, folder, root, sched_path, records=None):
    """the `result` column of the done items of the schedule whose node is this experiment: the folder (relative to the problem) that holds its
    results.md. Returns (linked item ids, note)."""
    import project as P
    import schedule as S
    if not os.path.exists(sched_path):
        return [], "no schedule: no link"
    rel = os.path.relpath(folder, root).replace("\\", "/")
    linked = []
    with P.locked(sched_path):
        rows = S.load(sched_path)
        state = {r["item"]: r["state"] for r in S.derived(rows, records)} if rows else {}
        for r in rows:
            if (r.get("node") or "").strip() == str(exp_id) and state.get(r["item"]) == "done" and r.get("result") != rel:
                try:
                    S.link(rows, r["item"], rel, root)
                except SystemExit as e:  # no results.md in the folder, an odd path: say so, link nothing
                    return [], str(e)
                linked.append(r["item"])
        if linked:
            S.save(rows, sched_path, lock=False)
    return linked, ("linked: " + ", ".join(linked)) if linked else f"no done schedule item with node {exp_id}: no link"


def warn_on(what, fn, *args):
    """fn(*args), or None after a printed warning: what is written after the ledger and decision.json is a side record, a lock timeout or an unreadable file must not undo the verdict"""
    try:
        return fn(*args)
    except (Exception, SystemExit) as e:  # noqa: BLE001
        print(f"  warning: {what} not written ({type(e).__name__}: {e})")
        return None


def update_topics(exp, d, root):
    """the result line of every research note the card cites (`sources`: '<topic slug>/<note id>'), then the table of each topic again (topic_table.py); the text comes
    only from the decision. Returns the messages: a failure is a warning message, never an exception"""
    import experiment as X
    import project as P
    import topic_table as TT
    text = f"{d['id']}: {d['verdict']} effect {d['effect']:+.4f}" + (" (by hand)" if d.get("by_hand") else " (rule not registered)" if d.get("registered") is False else "")
    topics = os.path.join(root, P.cfg_of(root).get("research", "literature"), "topics")
    msgs, folders = [], []
    for src in dict.fromkeys(exp.get("sources") or []):
        if not isinstance(src, str) or not X.SOURCE.fullmatch(src):
            msgs.append(f"warning: source {src!r} is not '<topic slug>/<note id>': not updated")
            continue
        slug, _, note = src.partition("/")
        folder = os.path.join(topics, slug)
        if not os.path.isdir(folder):
            msgs.append(f"warning: topic folder {folder} does not exist: {src} not updated")
            continue
        try:
            code, msg = TT.set_result(folder, note, text)
        except Exception as e:  # noqa: BLE001
            code, msg = 1, f"{type(e).__name__}: {e}"
        msgs.append(msg if not code else f"warning: {src}: {msg}")
        if not code and folder not in folders:
            folders.append(folder)
    for folder in folders:
        try:
            code, out = TT.run(folder)
        except Exception as e:  # noqa: BLE001
            code, out = 1, [f"{type(e).__name__}: {e}"]
        msgs += out if not code else [f"warning: table of {os.path.basename(folder)} not made: " + "; ".join(out)]
    return msgs

def record(path, exp, d, root):
    """the three records of a verdict (see the top of the file); `path` is the card file, `d` the decision (decision.json), `root` the problem folder. Prints one line per record"""
    import project as P
    folder = os.path.dirname(path)
    res = warn_on("results.md", write_results_md, folder, d, exp)
    if res:
        print(f"  results.md: {res[1]} ({res[0]})")
    if os.path.isfile(os.path.join(folder, "results.md")):
        if os.path.normcase(os.path.realpath(P.root())) == os.path.normcase(os.path.realpath(root)):
            link = warn_on("schedule link", lambda: link_schedule(exp["id"], folder, root, P.path("schedule"), P.path("run_records")))
            if link:
                print("  schedule: " + link[1])
        else:
            print("  schedule: another problem than AR_PROJECT: no link")
    for m in warn_on("research notes", update_topics, exp, d, root) or []:
        print("  " + m)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("experiment", help="experiment id (E240), folder, experiment.md or experiment.json")
    ap.add_argument("--check", action="store_true", help="say what would be written, change nothing")
    a = ap.parse_args()
    import decide as DC
    import experiment as X
    exp, path = X.load(a.experiment)
    dpath = DC.decision_path(path)
    if not os.path.isfile(dpath):
        sys.exit(f"{exp.get('id')}: no {os.path.basename(dpath)} next to the card: decide it first (decide.py --experiment {exp.get('id')} --write)")
    try:
        with open(dpath, encoding="utf-8") as f:
            d = json.load(f)
    except (OSError, ValueError) as e:
        sys.exit(f"{dpath} cannot be read ({e})")
    if not isinstance(d, dict) or not d.get("verdict"):
        sys.exit(f"{dpath} holds no verdict")
    if a.check:
        print(f"{exp.get('id')}: {d['verdict']} ({d.get('date')}): would write results.md in {os.path.dirname(path)}, link the done schedule items of node {exp.get('id')}, "
              f"update {len(exp.get('sources') or [])} research note(s)")
        return 0
    record(path, exp, d, X.problem_of(path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
