def effects(s, rung=0, key="S"):
    """L8 main effects of S (and of the other metrics) at rung 0: level 2 minus level 1 over the last run of every design"""
    vals = {}
    for d in DESIGNS:
        rs = design_runs(s, d, rung)
        c = card(rs[-1][1]["name"]) if rs else None
        if c and "metrics" in c:
            vals[d] = c["metrics"]
    if len(vals) < 8:
        return None
    sp, band = noise_band(control_table())
    sigma = sp / 1.13 if not np.isnan(sp) else 0.01  # E|X - Y| = 1.13 sigma for two draws of the same normal
    se = 0.71 * max(sigma, 0.005)
    out = []
    for i, f in enumerate(FACTORS):
        a = np.mean([vals[d][key] for d in DESIGNS if LEVELS[d][i] == 1])
        b = np.mean([vals[d][key] for d in DESIGNS if LEVELS[d][i] == 2])
        out.append((f, float(b - a), se, abs(b - a) > 2 * se))
    return out


