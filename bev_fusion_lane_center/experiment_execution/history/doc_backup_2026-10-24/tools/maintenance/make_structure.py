def size_count(p):
    tot = n = 0
    for dp, dn, fn in os.walk(p):
        for f in fn:
            try:
                tot += os.path.getsize(os.path.join(dp, f))
                n += 1
            except OSError:
                pass
    return tot, n


def fmt(b):
    return f"{b/1e9:.1f} GB" if b >= 1e9 else f"{b/1e6:.0f} MB" if b >= 1e6 else f"{b/1e3:.0f} kB"


def main():
    lines = ["# Structure of bev_fusion_lane_center", "", f"Generated {time.strftime('%Y-%m-%d %H:%M')} by `tools/maintenance/make_structure.py`. Sizes and file counts are recursive.", "", "```"]
    top = sorted(d for d in os.listdir(ROOT) if not d.startswith("."))
    order = ["README.md", "CLAUDE.md", "HANDOVER.md", "CONVENTIONS.md", "STRUCTURE.md", "literature", "experiment_execution", "experiments", "training", "evaluation", "tools", "reports", "temp", "runs", "models", "data", "downloads", "_to_delete"]
    top = [t for t in order if t in top] + [t for t in top if t not in order]
    for t in top:
        p = os.path.join(ROOT, t)
        if os.path.isdir(p):
            s, n = size_count(p)
            lines.append(f"{t + '/':26s} {fmt(s):>8s} {n:>6d} files   {PURPOSE.get(t, '')}")
            for sub in sorted(os.listdir(p)):
                q = os.path.join(p, sub)
                key = f"{t}/{sub}"
                if os.path.isdir(q) and (key in PURPOSE):
                    s2, n2 = size_count(q)
                    lines.append(f"  {sub + '/':24s} {fmt(s2):>8s} {n2:>6d} files   {PURPOSE[key]}")
        else:
            lines.append(f"{t:26s} {fmt(os.path.getsize(p)):>8s}               {PURPOSE.get(t, '')}")
    lines += ["```", "", "Not inside this folder: the WSL distribution disk `C:\\ML-Experiment\\wsl` (Ubuntu ext4 image) and, in the WSL home, the cached feature arrays and the clones of the foundation code - see `data/README.md`.", ""]
    open(os.path.join(ROOT, "STRUCTURE.md"), "w", encoding="utf-8").write("\n".join(lines))
    print("STRUCTURE.md written")
    # checkpoint registry
    rows = []
    runs = os.path.join(ROOT, "runs")
    for dp, dn, fn in os.walk(runs):
        for f in fn:
            if f.endswith((".pt", ".pth")):
                p = os.path.join(dp, f)
                sz = os.path.getsize(p)
                if sz < 1_000_000:
                    continue
                h = hashlib.sha256()
                with open(p, "rb") as fh:
                    for chunk in iter(lambda: fh.read(8 << 20), b""):
                        h.update(chunk)
                rows.append((os.path.relpath(p, runs).replace(os.sep, "/"), sz, time.strftime("%Y-%m-%d", time.localtime(os.path.getmtime(p))), h.hexdigest()[:12]))
    rows.sort()
    md = ["# All checkpoints under runs/ (generated)", "", f"{len(rows)} files >= 1 MB, total {fmt(sum(r[1] for r in rows))}. Regenerate: `python tools/maintenance/make_structure.py`. The curated list of the models that matter is `README.md` in this folder.", "",
          "| file (relative to runs/) | size | date | sha256[:12] |", "|---|---|---|---|"]
    md += [f"| {r[0]} | {r[1]/1e6:.1f} MB | {r[2]} | {r[3]} |" for r in rows]
    os.makedirs(os.path.join(ROOT, "models"), exist_ok=True)
    open(os.path.join(ROOT, "models", "REGISTRY_ALL.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    print("models/REGISTRY_ALL.md written:", len(rows), "checkpoints")


if __name__ == "__main__":
    main()
