def rewrite_md(s):
    md = open(MD, encoding="utf-8").read()
    for head, fn in SECTIONS:
        a = md.index(head)
        b = md.find("\n### ", a + 5)
        seg = md[a:b if b > 0 else len(md)]
        lines = seg.split("\n")
        # keep the heading and the explanatory lines before the first table row, replace the table
        k = next(i for i, ln in enumerate(lines) if ln.startswith("|"))
        e = k
        while e < len(lines) and lines[e].startswith("|"):
            e += 1
        new = "\n".join(lines[:k]) + "\n" + fn(s) + "\n" + "\n".join(lines[e:])
        md = md[:a] + new + (md[b:] if b > 0 else "")
    # header table
    run = [v["name"] for v in s["runs"].values() if is_running(v["name"])]
    hdr = f"| phase | {s['phase']} |\n| rung | {s['rung']} |\n| designs alive | {', '.join(s['alive'])} |\n| running jobs (run dirs) | {', '.join(run) or 'none'} |"
    md = re.sub(r"\| phase \|.*?\n\| rung \|.*?\n\| designs alive \|.*?\n\| running jobs.*?\|\n", hdr + "\n", md, flags=re.S)
    md = re.sub(r"## Next action\n\n.*?\n\n## Decision log", "## Next action\n\n" + s.get("next_action", "") + "\n\n## Decision log", md, flags=re.S)
    dl = "| time | rung | decision | reason |\n|---|---|---|---|\n" + "\n".join(f"| {d['time']} | {d['rung']} | {d['decision']} | {d['reason']} |" for d in s["decisions"])
    md = re.sub(r"\| time \| rung \| decision \| reason \|\n\|---\|---\|---\|---\|\n(\|.*\n)*", dl + "\n", md)
    open(MD, "w", encoding="utf-8").write(md)


