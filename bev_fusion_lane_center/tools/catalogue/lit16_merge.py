"""Merge the technique cards of the loop-16 literature research (report_final/text/lit16/*.md) into one table.
Reads every cluster file with `### CARD <ID> - <name>` blocks (format: SCHEMA.md), writes
  report_final/text/lit16/cards.csv        all fields
  report_final/text/lit16/cards_index.md   one line per card (stage, depth, differentiable, fit, verified)
  report_final/text/lit16/cards_stats.md   coverage statistics (cards per cluster / depth / stage / fit / differentiable)
Usage: python lit16_merge.py [dir]"""
import csv
import glob
import os
import re
import sys

D = sys.argv[1] if len(sys.argv) > 1 else "/mnt/c/ML-Experiment/bev_fusion_lane_center/literature/sources/lit16"
SKIP = {"PROJECT_CONTEXT.md", "SCHEMA.md", "eval_data_code.md", "cards_index.md", "cards_stats.md"}
FIELDS = ["id", "name", "cluster", "papers", "depth", "stage", "idea", "formulation", "input", "output", "training", "differentiable", "sensors_data", "results", "compute", "code", "fit_to_us",
          "compat_needs", "compat_conflicts", "tried_before", "verified"]
HEAD = re.compile(r"^###\s*CARD\s+(\S+)\s*[-–—:]\s*(.+?)\s*$")
FIELD = re.compile(r"^-\s*([a-z_]+)\s*:\s*(.*)$")


def parse_file(path):
    cards, cur, last = [], None, None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = HEAD.match(line)
        if m:
            cur = {"id": m.group(1), "name": m.group(2), "cluster": os.path.basename(path)[:-3]}
            cards.append(cur)
            last = None
            continue
        if cur is None:
            continue
        if line.startswith("## ") or line.startswith("# "):
            cur, last = None, None
            continue
        f = FIELD.match(line)
        if f and f.group(1) in FIELDS:
            last = f.group(1)
            cur[last] = f.group(2).strip()
        elif last and line.strip() and not line.startswith("###"):
            cur[last] += " " + line.strip()
    return cards


def first(s, n=1):
    return " ".join((s or "").replace("|", "/").split()[:n])


def main():
    cards = []
    for p in sorted(glob.glob(os.path.join(D, "*.md"))):
        if os.path.basename(p) in SKIP:
            continue
        cards += parse_file(p)
    with open(os.path.join(D, "cards.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, FIELDS)
        w.writeheader()
        for c in cards:
            w.writerow({k: c.get(k, "") for k in FIELDS})
    idx = ["# Card index (generated by scripts/lit16_merge.py)\n", f"{len(cards)} cards from {len({c['cluster'] for c in cards})} cluster files.\n",
           "| id | technique | stage | depth | differentiable | fit | verified | tried before |", "|---|---|---|---|---|---|---|---|"]
    for c in cards:
        idx.append(f"| {c['id']} | {c['name'].replace('|', '/')} | {first(c.get('stage'), 2)} | {first(c.get('depth'))} | {first(c.get('differentiable'))} | {first(c.get('fit_to_us'), 3)} | {first(c.get('verified'))} | {first(c.get('tried_before'), 4)} |")
    open(os.path.join(D, "cards_index.md"), "w", encoding="utf-8").write("\n".join(idx) + "\n")

    def count(key, fn=lambda s: first(s)):
        out = {}
        for c in cards:
            k = fn(c.get(key, "")) or "-"
            out[k] = out.get(k, 0) + 1
        return sorted(out.items(), key=lambda kv: -kv[1])

    st = ["# Card statistics (generated)\n"]
    for title, key, fn in (("cluster", "cluster", lambda s: s), ("depth", "depth", first), ("stage", "stage", lambda s: first(s, 1)), ("differentiable", "differentiable", first), ("fit", "fit_to_us", first), ("verified", "verified", first)):
        st.append(f"## by {title}\n")
        st.append("| value | cards |\n|---|---|")
        for k, v in count(key, fn):
            st.append(f"| {k} | {v} |")
        st.append("")
    open(os.path.join(D, "cards_stats.md"), "w", encoding="utf-8").write("\n".join(st) + "\n")
    print(len(cards), "cards")


if __name__ == "__main__":
    main()
