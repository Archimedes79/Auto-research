def do_cut(s, rung, tag=None):
    alive = s["alive"]
    n = len(alive)
    k = n // 2
    kills, scores = [], {}
    for d in alive:
        rs = design_runs(s, d, rung)
        best = None  # a refinement that hurts is dropped: the best checkpoint of the design (trial or refinement) counts and is the parent of the next rung
        for _, rr in rs:
            cc = card(rr["name"])
            cx = card(rr["name"] + "." + tag) if tag else cc
            if cc and cx and "metrics" in cx and (best is None or cx["metrics"]["S"] > best[2]["metrics"]["S"]):
                best = (rr, cc, cx)
        c, cm = (best[1], best[2]) if best else (None, None)
        if best:
            s.setdefault("best_run", {})[d] = best[0]["name"]
        if not c or not cm or "metrics" not in cm:
            kills.append((d, "no result"))
            continue
        m = cm["metrics"]
        if c.get("status", "ok") != "ok" or m["F1@1.0"] < 0.5 or not np.isfinite(m["S"]):
            kills.append((d, "kill switch (nan, divergence or F1@1 < 0.5)"))
        cost = sum((card(rr["name"]) or {}).get("train_seconds", 0.0) for _, rr in rs)  # total training seconds of the design in this rung (trial + refinement)
        scores[d] = (m["S"], cost, m)
    ranking = sorted(scores, key=lambda d: -scores[d][0])
    sp, band = noise_band(control_table())
    # ties at the cut boundary: a design ranked below the last survivor whose S lies inside the noise band of that survivor and that is cheaper (training seconds of its best run) takes the place
    order = list(ranking)
    keepn = n - k
    if len(order) > keepn:
        last = order[keepn - 1]
        for d in order[keepn:]:
            if scores[last][0] - scores[d][0] < band and scores[d][1] < scores[last][1]:
                i, j = order.index(last), order.index(d)
                order[i], order[j] = order[j], order[i]
                last = d
    survivors = [d for d in order if d not in [x for x, _ in kills]][:keepn]
    removed = [d for d in alive if d not in survivors]
    rules = []
    if kills:
        rules.append("kill: " + ", ".join(d for d, _ in kills))
    # metric-leader protection (rung 0 only): best J, best Sp, best F1@0.5 must stay
    if rung == 0:
        for key in ("J", "Sp", "F1@0.5"):
            vals = sorted([scores[d][2][key] for d in scores], reverse=True)
            if len(vals) < 2 or vals[0] - vals[1] <= 0.01:  # a tie at the top (the sparsity term saturates at 14.3 vertices per 100 m) leads nobody
                continue
            lead = max(scores, key=lambda d: scores[d][2][key])
            if lead in removed and lead not in [x for x, _ in kills]:
                worst = [d for d in reversed(survivors) if d not in (lead,)][0]
                survivors.remove(worst)
                survivors.append(lead)
                removed.remove(lead)
                removed.append(worst)
                rules.append(f"protection: {lead} leads {key}; {worst} cut instead")
    dec = {d: ("KEEP" if d in survivors else "CUT") for d in alive}
    ctrl = control_table()
    key = {0: 1, 1: 2, 2: 4, 3: 8}.get(rung, 1)
    cs = " / ".join(fmt(ctrl[(sd, key)]["S"]) if ctrl.get((sd, key)) else "—" for sd in (0, 1))
    s["cuts"][str(rung)] = dict(delta=band, control=cs, ranking=" > ".join(f"{d} {scores[d][0]:.3f}" for d in order), removed=", ".join(removed), rules="; ".join(rules) or "none", fl="see control curve", time=time.strftime("%Y-%m-%d %H:%M"), decisions=dec)
    s["alive"] = survivors
    decide(s, rung, f"rung {rung} cut: keep {', '.join(survivors)}; remove {', '.join(removed)}", f"ranking by S: {s['cuts'][str(rung)]['ranking']}; noise band {band:.3f}; {s['cuts'][str(rung)]['rules']}")
    return dec


def main():
    s = load()
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"
    if cmd == "init":
        s = load()
        save(s)
    elif cmd == "register":  # register an already launched run in the ledger: register D3 0 00 1 ["change text"]
        d_, r_, st_, u_ = sys.argv[2], int(sys.argv[3]), sys.argv[4], float(sys.argv[5])
        s["runs"][run_id(d_, r_, st_)] = dict(design=d_, rung=r_, step=st_, type="T", change=sys.argv[6] if len(sys.argv) > 6 else "trial as specified in the L8 row", hypothesis="", basis=BASIS[d_], parent="-", u=u_, seed=0, name=run_name(d_, r_, st_), launched=time.strftime("%Y-%m-%d %H:%M"), sets=[], ws=[])
        save(s)
    elif cmd == "note":  # note <rung> <decision> <reason>
        decide(s, int(sys.argv[2]), sys.argv[3], sys.argv[4])
        save(s)
    elif cmd == "next":  # next <text>
        s["next_action"] = sys.argv[2]
        save(s)
    elif cmd == "rung0":
        for d in DESIGNS:
            if d != "D3":
                enqueue(s, d, 0, "00", 1)
        s["phase"] = "rung 0 (trials queued)"
        s["rung"] = 0
        save(s)
        rewrite_md(s)
    elif cmd == "refresh":
        rewrite_md(s)
        save(s)
    elif cmd == "status":
        for rid, r in s["runs"].items():
            c = card(r["name"])
            st = "done" if c else ("running" if is_running(r["name"]) else "queued")
            print(rid, st, f"S {c['metrics']['S']:.3f}" if c and "metrics" in c else "")
        print("alive", s["alive"], "rung", s["rung"], "phase", s["phase"])
    elif cmd == "cut":
        print(do_cut(s, int(sys.argv[2]), sys.argv[3] if len(sys.argv) > 3 else None))
        rewrite_md(s)
        save(s)
    elif cmd == "launch":
        import argparse

        ap = argparse.ArgumentParser()
        ap.add_argument("cmd")
        ap.add_argument("design")
        ap.add_argument("rung", type=int)
        ap.add_argument("step")
        ap.add_argument("u", type=float)
        ap.add_argument("--parent", default=None)
        ap.add_argument("--set", nargs="*", default=[])
        ap.add_argument("--w", nargs="*", default=[])
        ap.add_argument("--type", default="T")
        ap.add_argument("--change", default="trial as specified in the L8 row")
        ap.add_argument("--hyp", default="")
        ap.add_argument("--basis", default=None)
        ap.add_argument("--seed", type=int, default=0)
        a = ap.parse_args()
        print(launch(s, a.design, a.rung, a.step, a.u, a.parent, a.set, a.w, a.type, a.change, a.basis, a.seed, a.hyp))
        save(s)
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
